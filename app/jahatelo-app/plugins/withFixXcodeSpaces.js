const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

/**
 * Fix para proyectos con espacios en la ruta del proyecto.
 * Xcode genera scripts en DerivedData con PROJECT_ROOT="$PROJECT_DIR"/..
 * (comillas cierran antes del /..), lo que rompe rutas con espacios.
 * Además, $(command -v node) en .xcode.env se expande sin comillas y falla.
 * Este plugin crea ios/.xcode.env.local con NODE_BINARY absoluto y PROJECT_ROOT seguro.
 */
function withFixXcodeSpaces(config) {
  return withDangerousMod(config, [
    'ios',
    (exportedConfig) => {
      const projectRoot = exportedConfig.modRequest.projectRoot;
      const iosDir = path.join(projectRoot, 'ios');
      const xcodeEnvLocal = path.join(iosDir, '.xcode.env.local');

      // Resolver ruta absoluta de node sin espacios
      let nodeBinary;
      try {
        nodeBinary = execSync('command -v node', { encoding: 'utf8' }).trim();
      } catch {
        nodeBinary = '/usr/local/bin/node';
      }

      const envContent = [
        '# Auto-generated by withFixXcodeSpaces plugin',
        '# Fixes space-in-path issue for Bundle React Native code and images',
        `export NODE_BINARY="${nodeBinary}"`,
        'export PROJECT_ROOT="$SRCROOT/.."',
        '',
      ].join('\n');

      fs.writeFileSync(xcodeEnvLocal, envContent, 'utf8');
      console.log(`[withFixXcodeSpaces] Created ios/.xcode.env.local (NODE_BINARY=${nodeBinary})`);

      return exportedConfig;
    },
  ]);
}

module.exports = withFixXcodeSpaces;